#include <iostream>
#include <clocale>

using namespace std;

int main() {
    setlocale(LC_ALL, "Russian");

    cout << "Вариант 12: проверка, является ли число степенью двойки" << endl;
    cout << "------------------------------------------------------" << endl;

    long long X;
    cout << "Введите целое число X: ";
    cin >> X;

    // Основная проверка через побитовую операцию
    bool isPowerOfTwo = (X > 0) && ((X & (X - 1)) == 0);

    // Вывод результата
    if (isPowerOfTwo) {
        cout << "Число " << X << " ЯВЛЯЕТСЯ степенью двойки." << endl;
    } else {
        cout << "Число " << X << " НЕ является степенью двойки." << endl;
    }

    // Дополнительно: показываем само выражение в действии (для отчёта)
    cout << "--------------------------------------" << endl;
    cout << "Проверка: (X > 0) && ((X & (X - 1)) == 0)" << endl;
    cout << "  X > 0           -> " << (X > 0) << endl;
    cout << "  X & (X - 1)     -> " << (X & (X - 1)) << endl;
    cout << "  (X & (X-1))==0  -> " << ((X & (X - 1)) == 0) << endl;

    return 0;
}